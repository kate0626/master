#!/usr/bin/env bash
set -euo pipefail
###############################################################################
# servers.conf を任意K台ぶん自動生成する (cap11.. の規則的ホスト用)。
#
#   host = cap<START+i>,  id = i,  ip = 10.58.59.<START+i>,  port = PORT
#
# 使い方:
#   bash base/new-many-server/gen_servers_conf.sh --count 4              # cap11..cap14
#   bash base/new-many-server/gen_servers_conf.sh --count 8 --start 11   # cap11..cap18
#   bash base/new-many-server/gen_servers_conf.sh --count 4 --stdout     # 標準出力のみ(上書きしない)
#
# 注意: 生成後は partition.sh --server-count <count> で分割も同じKで作り直すこと。
###############################################################################

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${SELF_DIR}/servers.conf"

COUNT=""
START=11          # cap11 から
IP_PREFIX="10.58.59"
PORT=3000
TO_STDOUT=0
MAX_HOST=26       # cap26 まで

usage() {
  cat <<EOF
Usage: bash base/new-many-server/gen_servers_conf.sh --count K [options]
  --count K       台数 (必須, 1..$((MAX_HOST-START+1)))
  --start N       開始ホスト番号 (default: ${START} = cap${START})
  --port P        RWサーバのポート (default: ${PORT})
  --stdout        ファイルに書かず標準出力へ
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --count) COUNT="${2:-}"; shift 2 ;;
    --start) START="${2:-}"; shift 2 ;;
    --port)  PORT="${2:-}"; shift 2 ;;
    --stdout) TO_STDOUT=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

[[ -z "${COUNT}" ]] && { echo "--count is required" >&2; usage; exit 1; }
[[ "${COUNT}" =~ ^[0-9]+$ ]] || { echo "--count must be an integer" >&2; exit 1; }
(( COUNT >= 1 )) || { echo "--count must be >= 1" >&2; exit 1; }
last=$(( START + COUNT - 1 ))
(( last <= MAX_HOST )) || { echo "cap${last} は範囲外 (cap${START}..cap${MAX_HOST} まで)。--count/--start を調整。" >&2; exit 1; }

gen() {
  echo "# auto-generated by gen_servers_conf.sh (count=${COUNT} start=cap${START} port=${PORT})"
  echo "# host id ip port"
  for (( i=0; i<COUNT; i++ )); do
    n=$(( START + i ))
    printf "cap%d %d %s.%d %d\n" "${n}" "${i}" "${IP_PREFIX}" "${n}" "${PORT}"
  done
}

if (( TO_STDOUT == 1 )); then
  gen
else
  gen > "${OUT}"
  echo ">>> wrote ${OUT} (${COUNT} servers: cap${START}..cap${last})"
  cat "${OUT}"
fi
